"""Regenerates app/grpc_gen from backend/src/Erp.Api/Protos/ai_assistant.proto (the shared contract).

    cd ai-service && python scripts/gen_proto.py          # needs grpcio-tools (requirements-dev.txt)

The stubs are committed so the Docker build (context ./ai-service) doesn't need the backend folder.
tests/test_grpc.py::test_stubs_match_proto fails when they are stale.
"""
import re
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PROTO_DIR = ROOT.parent / "backend" / "src" / "Erp.Api" / "Protos"
PROTO = "ai_assistant.proto"
OUT = ROOT / "app" / "grpc_gen"
HEADER = "# Generated by scripts/gen_proto.py from backend/src/Erp.Api/Protos/ai_assistant.proto. Do not edit.\n"


def generate(out_dir: Path) -> dict[str, str]:
    """Runs protoc into out_dir; returns {file name: content} with the relative import fixed."""
    from grpc_tools import protoc

    code = protoc.main(["grpc_tools.protoc", f"-I{PROTO_DIR}", f"--python_out={out_dir}",
                        f"--pyi_out={out_dir}", f"--grpc_python_out={out_dir}", str(PROTO_DIR / PROTO)])
    if code != 0:
        raise SystemExit(f"protoc failed ({code})")
    files = {}
    for path in sorted(out_dir.glob("ai_assistant_pb2*")):
        text = path.read_text(encoding="utf-8")
        # protoc emits `import ai_assistant_pb2 as ...`; inside the package it must be relative
        text = re.sub(r"^import ai_assistant_pb2 as", "from . import ai_assistant_pb2 as", text, flags=re.M)
        files[path.name] = HEADER + text
    return files


def main() -> None:
    with tempfile.TemporaryDirectory() as tmp:
        files = generate(Path(tmp))
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "__init__.py").write_text('"""Generated gRPC stubs (see scripts/gen_proto.py)."""\n', encoding="utf-8")
    for name, text in files.items():
        (OUT / name).write_text(text, encoding="utf-8", newline="\n")
        print("wrote", (OUT / name).relative_to(ROOT))


if __name__ == "__main__":
    sys.exit(main())
